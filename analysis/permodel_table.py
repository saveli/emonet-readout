#!/usr/bin/env python
"""Per-model body table (tables/permodel.tex) from the result JSONs.

Columns, five categories, held-out mapping: text, matched resolution, P(yes); then P(yes) minus
each reference with a star where the paired CI excludes 0: the three-expert panel (model mapped
to the panel's marginal, vs the held-out expert), Empathic-Insight-Face Small and Large. Each
input JSON's provenance is checked against the current scoring module first.

Usage:
    python analysis/permodel_table.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import scoring as s2  # noqa: E402
from controls_common import tex_name  # noqa: E402


def main() -> int:
    J = {}
    for name in ("fleet", "matched_resolution", "anchor_three_rater", "eif_significance"):
        J[name] = json.load(open(s2.RESULTS_DIR / f"{name}.json"))
        s2.check_provenance(J[name]["provenance"], B=s2.B_CI, label=name,
                            need=(("results_verify_prefill",) if name == "eif_significance"
                                  else ("results_e0", "results_verify_prefill")))
    fl = J["fleet"]["sets"]["reliable_5"]["estimators"]["heldout"]["conditions"]
    text = {r["model"]: r["kappa"] for r in fl["text"]["rows"]}
    pyes = {r["model"]: r["kappa"] for r in fl["pyes"]["rows"]}
    matched = {r["model"]: r["kappa_matched"]
               for r in J["matched_resolution"]["estimators"]["heldout"]["rows"]}
    panel = {r["model"]: r for r in J["anchor_three_rater"]["sets"]["reliable_5"]["rows"]
             if r["condition"] == "pyes" and r["estimator"] == "heldout"
             and r["comparison"] == "loro_vs_panel"}
    eif = {(r["model"], r["reference_key"]): r for r in J["eif_significance"]["rows"]
           if r["estimator"] == "heldout" and r["category_set"] == "reliable_5"}
    models = sorted(text, key=lambda t: tex_name(t).casefold())

    def star(diff, ci_):
        sig = ci_[0] > 0 or ci_[1] < 0
        return f"${diff:+.3f}{'^{*}' if sig else ''}$"

    def counts(rows):
        return (sum(r[1][0] > 0 for r in rows), sum(r[1][1] < 0 for r in rows))

    lines = ["% generated by analysis/permodel_table.py from results/{fleet, matched_resolution,",
             "% anchor_three_rater, eif_significance}.json -- do not edit by hand. Five categories,",
             "% held-out mapping; * = paired image-bootstrap 95% CI (B=500) excludes 0.",
             r"\begin{tabular}{lcccccc}", r"\toprule",
             r" & \multicolumn{3}{c}{$\kappa_w$} & \multicolumn{3}{c}{$P(\mathrm{yes})$ $-$ reference} \\",
             r"\cmidrule(lr){2-4}\cmidrule(lr){5-7}",
             r"Model & text & matched & P(yes) & 3 experts & EIF S & EIF L \\", r"\midrule"]
    cols = {"panel": [], "eif_small": [], "eif_large": []}
    for t in models:
        p = panel[t]
        es, el = eif[(t, "eif_small")], eif[(t, "eif_large")]
        cols["panel"].append((p["diff"], p["ci"]))
        cols["eif_small"].append((es["diff"], es["diff_ci"]))
        cols["eif_large"].append((el["diff"], el["diff_ci"]))
        lines.append(f"{tex_name(t)} & ${text[t]:.3f}$ & ${matched[t]:.3f}$ & ${pyes[t]:.3f}$ & "
                     f"{star(p['diff'], p['ci'])} & {star(es['diff'], es['diff_ci'])} & "
                     f"{star(el['diff'], el['diff_ci'])} \\\\")
    mean = lambda d: sum(d.values()) / len(d)  # noqa: E731
    cnt = {k: counts(v) for k, v in cols.items()}
    lines += [r"\midrule",
              f"Mean, sig.\\ $>$\\,/\\,$<$ & ${mean(text):.3f}$ & ${mean(matched):.3f}$ & "
              f"${mean(pyes):.3f}$ & " + " & ".join(f"${a}\\,/\\,{b}$" for a, b in cnt.values())
              + r" \\", r"\bottomrule", r"\end{tabular}", ""]
    tex = "\n".join(lines)
    s2.write_tex(s2.TABLES_DIR / "permodel.tex", tex)
    s2.write_tex(Path("tables/permodel.tex"), tex)
    print("significant above / below: " + ", ".join(f"{k} {a}/{b}" for k, (a, b) in cnt.items()))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
