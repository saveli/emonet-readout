#!/usr/bin/env python
"""Write tables/rate.tex (graded-digit control, supplementary A_rate) from
results/rate_control.json. Held-out estimator, five categories, 500-image subset.
Run: python analysis/rate_table.py"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
NAMES = {"GLM-4.6V-Flash": "GLM-4.6V-Flash", "InternVL3_5-8B-HF": "InternVL3\\_5-8B",
         "MiMo-VL-7B-RL-2508": "MiMo-VL-7B-RL", "MiniCPM-V-4.6": "MiniCPM-V-4.6",
         "Ministral-3-14B-Instruct-2512": "Ministral-3-14B", "Qwen2.5-VL-3B-Instruct": "Qwen2.5-VL-3B",
         "Qwen3-VL-8B-Instruct": "Qwen3-VL-8B", "Qwen3.5-9B": "Qwen3.5-9B",
         "gemma-3-12b-it": "Gemma-3-12b-it", "gemma-3-4b-it": "Gemma-3-4b-it",
         "gemma-4-12B-it": "Gemma-4-12B-it"}


def sig(d, ci):
    star = "^{*}" if (ci[0] > 0 or ci[1] < 0) else ""
    return f"${d:+.3f}{star}$"


def main():
    d = json.load(open(ROOT / "results/rate_control.json"))
    e = d["estimators"]["heldout"]
    rows = sorted(e["rows"], key=lambda r: NAMES[r["model"]].lower())
    out = ["% generated by analysis/rate_table.py from results/rate_control.json -- do not edit by hand",
           "% five categories, 500-image subset, held-out mapping; * = paired 95% CI excludes 0",
           "\\begin{tabular}{lccccccc}", "\\toprule",
           "Model & text & argmax & expected & P(yes) & exp.$-$argm. & P(yes)$-$exp. & mass \\\\",
           "\\midrule"]
    for r in rows:
        name = NAMES[r["model"]] + ("$^{\\dagger}$" if r["resolution_confound"] else "")
        out.append(f"{name} & ${r['kappa_text']:.3f}$ & ${r['kappa_argmax']:.3f}$ & "
                   f"${r['kappa_expected']:.3f}$ & ${r['kappa_pyes']:.3f}$ & "
                   f"{sig(r['expected_minus_argmax'], r['expected_minus_argmax_ci'])} & "
                   f"{sig(r['pyes_minus_expected'], r['pyes_minus_expected_ci'])} & "
                   f"${r['digit_mass']:.3f}$ \\\\")
    f = e["fleet"]
    out += ["\\midrule",
            f"Mean & ${f['kappa_text']:.3f}$ & ${f['kappa_argmax']:.3f}$ & ${f['kappa_expected']:.3f}$ & "
            f"${f['kappa_pyes']:.3f}$ & {sig(f['expected_minus_argmax'], f['expected_minus_argmax_ci'])} & "
            f"{sig(f['pyes_minus_expected'], f['pyes_minus_expected_ci'])} & ${f['digit_mass_mean']:.3f}$ \\\\",
            "\\bottomrule", "\\end{tabular}"]
    (ROOT / "tables/rate.tex").write_text("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
